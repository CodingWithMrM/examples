// Turns screen/*.jsx into src/hyd/samples.ts so the video shows EXACTLY the files that were run (minus the first comment line).
//   node gen-samples.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const dir = import.meta.dirname + "/screen";
const out = {};
for (const f of readdirSync(dir).filter((x) => /\.(jsx|css)$/.test(x))) {
  const lines = readFileSync(`${dir}/${f}`, "utf8").replace(/\n$/, "").split("\n");
  if (lines[0].startsWith("//") || lines[0].startsWith("/*")) lines.shift();
  out[f.replace(/\.(jsx|css)$/, "")] = lines;
}
writeFileSync(import.meta.dirname + "/../../../../src/hyd/samples.ts", "// GENERATED by videos/06-hydration-mismatch/3-work/code/gen-samples.mjs from screen/*.jsx. Do not edit.\nexport const SAMPLES: Record<string, string[]> = " + JSON.stringify(out, null, 1) + ";\n");
console.log(Object.keys(out).join(", "));
